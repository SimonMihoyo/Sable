-- ============================================================
-- 数据源名称唯一 —— 支撑错误码 40203「数据源名称重复」
-- ============================================================
-- 用**部分**唯一索引而不是唯一约束：data_source 是软删的（deleted_at + V1 里的部分索引），
-- 已删除的数据源不该继续占用名称，否则"删掉后重建同名"会被数据库挡住。
--
-- 应用层的查重只负责给一句可读的提示；真正的兜底是这条索引 —— 两个并发请求可以
-- 同时通过前置检查，只有数据库能保证最终只有一个写入成功（冲突由服务层翻译成 40203）。
CREATE UNIQUE INDEX uq_ds_name_active ON data_source (name) WHERE deleted_at IS NULL;
